#!/usr/bin/env python3
"""Rasterise the glyphs the UI needs (ASCII plus every non-ASCII character found in the given source file) from a
TrueType/OpenType font into include/font_cn.h, so the LCD can show Chinese without a font library on the board.
usage: genfont.py FONT.ttc FONT_INDEX SOURCE.cc OUT.h"""
import sys
from PIL import Image, ImageDraw, ImageFont

font_path, index, src, out = sys.argv[1], int(sys.argv[2]), sys.argv[3], sys.argv[4]
text = open(src, encoding="utf-8").read()
cps = sorted(set(range(32, 127)) | {ord(c) for c in text if ord(c) > 127 and ord(c) < 0x10000})
sizes = [16, 22]

lines = ["// generated by tools/genfont.py, do not edit", "#pragma once",
         "struct CnGlyph { unsigned short cp; unsigned char w, h; signed char bx, by; unsigned char adv; unsigned int off; };"]
for size in sizes:
    font = ImageFont.truetype(font_path, size, index=index)
    bits, glyphs = [], []
    for cp in cps:
        ch = chr(cp)
        adv = int(round(font.getlength(ch)))
        l, t, r, b = font.getbbox(ch, anchor="ls")
        w, h = max(0, r - l), max(0, b - t)
        off = len(bits)
        if w and h:
            img = Image.new("L", (w, h), 0)
            ImageDraw.Draw(img).text((-l, -t), ch, font=font, fill=255, anchor="ls")
            bits.extend(img.tobytes())
        glyphs.append((cp, w, h, l, t, adv, off))
    lines.append("static const unsigned char kCn%dBits[] = {%s};" % (size, ",".join(map(str, bits))))
    lines.append("static const CnGlyph kCn%d[] = {%s};" % (
        size, ",".join("{%d,%d,%d,%d,%d,%d,%d}" % g for g in glyphs)))
    lines.append("static const int kCn%dN = %d;" % (size, len(glyphs)))
open(out, "w", encoding="utf-8").write("\n".join(lines) + "\n")
print("glyphs:", len(cps), "bitmap bytes:", sum(len(l) for l in lines))
